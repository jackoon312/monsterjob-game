// Generates every MonsterJob sprite sheet from code.
//
//   node art-src/build.js
//
// For each module in art-src/creatures/ this writes:
//   - the sprite sheet to monsterjob-frontend/public<spriteAssetPath>, where
//     spriteAssetPath is read from monsterjob-backend/seed/seedSpecies.js so
//     the file can never drift from what the database points at
//   - a 4x contact sheet to art-src/contact/<name>-4x.png for review
// and then:
//   - art-src/preview-data.js (sheets as data URIs, used by preview.html)
//   - monsterjob-frontend/src/game/creatureSpriteManifest.json (what the
//     game is allowed to load)
// Output is deterministic: re-running without changes rewrites identical bytes.
const fs = require('node:fs');
const path = require('node:path');
const { encodePNG } = require('./lib/png');
const { compose, FRAME, BASELINE } = require('./lib/sprite');

const ROOT = path.join(__dirname, '..');
const SEED = path.join(ROOT, 'monsterjob-backend/seed/seedSpecies.js');
const PUBLIC = path.join(ROOT, 'monsterjob-frontend/public');
const MANIFEST = path.join(ROOT, 'monsterjob-frontend/src/game/creatureSpriteManifest.json');

const COLUMNS = 6;
const ANIMATIONS = [
  { name: 'idle', row: 0, fps: 6 },
  { name: 'work', row: 1, fps: 8 }
];
const COLOUR_LIMIT = { Common: 10, Uncommon: 10, Rare: 12, Epic: 12, Legendary: 12 };

// name -> { spriteAssetPath, rarity }, read straight from the seed file's text
// (requiring it would try to connect to MongoDB).
function readSeedSpecies() {
  const text = fs.readFileSync(SEED, 'utf8');
  const species = {};
  const entry = /name:\s*"([^"]+)"[\s\S]*?rarity:\s*"([^"]+)"[\s\S]*?spriteAssetPath:\s*"([^"]+)"/g;
  let m;
  while ((m = entry.exec(text))) species[m[1]] = { rarity: m[2], spriteAssetPath: m[3] };
  return species;
}

function validate(creature, seed) {
  const problems = [];
  const all = [];
  for (const anim of ANIMATIONS) {
    const frames = creature.frames[anim.name];
    if (!frames || frames.length !== COLUMNS) {
      problems.push(`${anim.name}: expected ${COLUMNS} frames, got ${frames ? frames.length : 0}`);
      continue;
    }
    frames.forEach((frame, i) => {
      if (frame.size !== FRAME) problems.push(`${anim.name}[${i}]: frame is not ${FRAME}px`);
      if (frame.clipped) problems.push(`${anim.name}[${i}]: pixels fall outside the frame`);
      if (frame.lowestRow() > BASELINE) problems.push(`${anim.name}[${i}]: drawn below the baseline (row ${BASELINE})`);
      all.push(frame);
    });
  }
  if (creature.frames.idle && creature.frames.idle[0].lowestRow() !== BASELINE) {
    problems.push(`idle[0]: feet must rest on the baseline (row ${BASELINE})`);
  }
  const colours = new Set();
  all.forEach((frame) => frame.colours().forEach((c) => colours.add(c)));
  const limit = COLOUR_LIMIT[seed.rarity];
  if (colours.size > limit) problems.push(`uses ${colours.size} colours, limit for ${seed.rarity} is ${limit}`);
  return { problems, all, colourCount: colours.size, limit };
}

function main() {
  const seedSpecies = readSeedSpecies();
  const previewData = {};
  const sheets = [];
  const files = fs.readdirSync(path.join(__dirname, 'creatures')).filter((f) => f.endsWith('.js')).sort();

  for (const file of files) {
    const creature = require(path.join(__dirname, 'creatures', file));
    const seed = seedSpecies[creature.species];
    if (!seed) throw new Error(`${file}: species "${creature.species}" is not in seedSpecies.js`);

    const { problems, all, colourCount, limit } = validate(creature, seed);
    if (problems.length) throw new Error(`${creature.species} failed validation:\n  - ${problems.join('\n  - ')}`);

    const sheet = compose(all, COLUMNS);
    const sheetPng = encodePNG(sheet.width, sheet.height, sheet.rgba);
    const outPath = path.join(PUBLIC, seed.spriteAssetPath);
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    fs.writeFileSync(outPath, sheetPng);

    const contact = compose(all, COLUMNS, { scale: 4, background: '#2b2118', gap: 8 });
    const slug = path.basename(seed.spriteAssetPath, '.png');
    fs.writeFileSync(path.join(__dirname, 'contact', `${slug}-4x.png`), encodePNG(contact.width, contact.height, contact.rgba));

    previewData[creature.species] = `data:image/png;base64,${sheetPng.toString('base64')}`;
    sheets.push(seed.spriteAssetPath);
    console.log(`${creature.species}: ${sheet.width}x${sheet.height}, ${colourCount}/${limit} colours -> ${path.relative(ROOT, outPath)}`);
  }

  const spec = { frameWidth: FRAME, frameHeight: FRAME, columns: COLUMNS, animations: ANIMATIONS };
  fs.writeFileSync(
    path.join(__dirname, 'preview-data.js'),
    `// Generated by art-src/build.js - do not edit.\nwindow.MONSTERJOB_ART = ${JSON.stringify({ ...spec, sheets: previewData }, null, 2)};\n`
  );
  fs.writeFileSync(MANIFEST, JSON.stringify({ ...spec, sheets }, null, 2) + '\n');
}

main();
